public class RelationalOperators {
    public static void main(String[] args) {
        System.out.println("Relational Operators in Java");

        int a = 10;
        int b = 5;

        System.out.println( a + " == " + b + " : " + (a == b));
        System.out.println( a + " != " + b + " : " + (a != b));
        System.out.println( a + " > " + b + " : " + (a > b));
        System.out.println( a + " < " + b + " : " + (a < b));
        System.out.println( a + " >= " + b + " : " + (a >= b));
        System.out.println( a + " <= " + b + " : " + (a <= b));
    }
}